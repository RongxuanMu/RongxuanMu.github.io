"""Build the VibeXR Interaction Framework site page from the CodePen source.

  codepen.html  the source of truth: exactly what goes in the CodePen HTML panel (no <head>, three.js from
                jsDelivr through the import map). Edit it here or on CodePen, then copy it across so both match.
  index.html    generated: the same markup wrapped in a full HTML document for GitHub Pages.

Microduck XR (../microduck-xr/build.py) and Immersive Vibe (../immersive-vibe/build.py) also build on codepen.html,
so rebuild them after a framework change if they should pick it up."""
from pathlib import Path
import re

P = Path(__file__).resolve().parent
src = (P / 'codepen.html').read_text()

m = re.search(r'var VERSION = "([^"]+)";', src)
assert m, 'VERSION not found in codepen.html'
version = m.group(1)
assert f'VibeXR Interaction Framework v{version}' in src.split('\n', 1)[0], \
    'the header comment and VERSION disagree; bump both'

description = ('VibeXR is a single-file WebXR interaction framework: hands, controllers, gaze and a mouse share one '
               'model of point, pinch, poke and grab, in passthrough by default.')

page = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>VibeXR Interaction Framework v{version}</title>
<meta name="description" content="{description}">
<meta property="og:type" content="website">
<meta property="og:title" content="VibeXR Interaction Framework - Rongxuan Mu">
<meta property="og:description" content="{description}">
<meta property="og:url" content="https://rongxuanmu.github.io/vibexr/">
<meta property="og:image" content="https://rongxuanmu.github.io/Resources/vibexr-framework/VibeXRFramework.jpg">
<meta name="twitter:card" content="summary_large_image">
<link rel="icon" href="../Resources/common/favicon-64.png" type="image/png">
</head>
<body>
<!-- Generated by vibexr/build.py from vibexr/codepen.html. Edit codepen.html, not this file. -->
{src.rstrip()}
</body>
</html>
'''
(P / 'index.html').write_text(page)
print(f'vibexr/index.html built from codepen.html (framework v{version})')
