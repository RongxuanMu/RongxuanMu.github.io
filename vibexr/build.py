"""Build the VibeXR Interaction Framework site pages from the CodePen source.

  codepen.html      the stable source of truth: exactly what goes in the CodePen HTML panel (no <head>, three.js
                    from jsDelivr through the import map). Edit it here or on CodePen, then copy it across.
  index.html        generated: the same markup wrapped in a full HTML document  ->  /vibexr/
  dev/codepen.html  work in progress, for testing in a headset before it replaces the stable version
  dev/index.html    generated, unlinked and not indexed  ->  /vibexr/dev/

  python3 vibexr/build.py            build both pages
  python3 vibexr/build.py --promote  copy dev/codepen.html over codepen.html, then build

Microduck XR (../microduck-xr/build.py) and Immersive Vibe (../immersive-vibe/build.py) also build on codepen.html,
so rebuild them after a framework change if they should pick it up."""
from pathlib import Path
import re
import shutil
import sys

import landing

# the update line on each page's card (the landing layout itself comes from landing.py; CodePen's own
# framework 0.8.28 does the same natively)
STABLE_NOTE = ('13 Oct 2026', 'one Enter button: passthrough by default, VR where a headset has no AR')
DEV_NOTE = ('16 Oct 2026', 'beta: keyboard and mouse - Unity-style navigation on desktop (right-drag look, right + WASD / QE fly, '
                           'middle-drag pan, Alt + left orbit, F frame), keyboard and mouse in XR where the browser passes them')

P = Path(__file__).resolve().parent
DEV = P / 'dev'

description = ('VibeXR is a single-file WebXR interaction framework: hands, controllers, gaze and a mouse share one '
               'model of point, pinch, poke and grab, in passthrough by default.')


def build(folder, root, dev):
    src = (folder / 'codepen.html').read_text()
    m = re.search(r'var VERSION = "([^"]+)";', src)
    assert m, f'VERSION not found in {folder.name}/codepen.html'
    version = m.group(1)
    assert f'VibeXR Interaction Framework v{version}' in src.split('\n', 1)[0], \
        f'{folder.name}/codepen.html: the header comment and VERSION disagree; bump both'
    if dev:
        meta = '<meta name="robots" content="noindex">'
        title = f'VibeXR dev v{version}'
    else:
        meta = f'''<meta name="description" content="{description}">
<meta property="og:type" content="website">
<meta property="og:title" content="VibeXR Interaction Framework - Rongxuan Mu">
<meta property="og:description" content="{description}">
<meta property="og:url" content="https://rongxuanmu.com/vibexr/">
<meta property="og:image" content="https://rongxuanmu.com/Resources/vibexr-framework/VibeXRFramework.jpg">
<meta name="twitter:card" content="summary_large_image">'''
        title = f'VibeXR Interaction Framework v{version}'
    page = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>{title}</title>
{meta}
<link rel="icon" href="{root}Resources/common/favicon-64.png" type="image/png">
</head>
<body>
<!-- Generated by vibexr/build.py from {folder.relative_to(P.parent).as_posix()}/codepen.html. Edit that file, not this one. -->
{landing.apply(src, *(DEV_NOTE if dev else STABLE_NOTE)).rstrip()}
</body>
</html>
'''
    (folder / 'index.html').write_text(page)
    print(f'{folder.relative_to(P.parent).as_posix()}/index.html built (framework v{version})')


if '--promote' in sys.argv:
    shutil.copyfile(DEV / 'codepen.html', P / 'codepen.html')
    print('promoted dev/codepen.html -> codepen.html')
build(P, '../', dev=False)
if (DEV / 'codepen.html').exists():
    build(DEV, '../../', dev=True)
