"""Build Archiscape Quest: the Archiscape town builder (archiscape/src/*.js) turned puzzle game by src/quest.js -
little figures walk the town one storey at a step, and you shape their way with a budget of blocks.
Unlisted: noindex, linked from nowhere on the site.
  index.html    the full page for GitHub Pages  ->  /archiscape-quest/

  python3 archiscape-quest/build.py"""
from pathlib import Path
import sys
import re

P = Path(__file__).resolve().parent
s = (P.parent / 'vibexr' / 'codepen.html').read_text()


def swap(a, b):
    global s
    assert s.count(a) == 1, a
    s = s.replace(a, b)


version = re.search(r'var VERSION = "([^"]+)";', s).group(1)

# world: the playground section is replaced wholesale; the framework modules stay untouched
AS = P.parent / 'archiscape' / 'src'
world = '\n'.join((AS / f).read_text().rstrip() for f in ('core.js', 'styles.js', 'music.js', 'world.js')) + '\n' + (P / 'src' / 'quest.js').read_text().rstrip()
a = s.index('// src/worlds/playground.js')
b = s.index('// src/main.js\nvar VERSION')
s = s[:a] + world + '\n\n' + s[b:]
swap('this.worlds.register(Playground);', 'this.worlds.register(ArchiscapeQuest);')
swap('await app.worlds.load("playground");', 'await app.worlds.load("archiscape-quest");')

# page chrome (the one Enter button is the framework's, unchanged)
swap(f'<!-- VibeXR Interaction Framework v{version} - single-file build',
     '<!-- Archiscape Quest - a puzzle prototype on the Archiscape town builder: shape the way for little figures with a\n'
     '  budget of blocks. Level 1, the Wooden Horse at Troy. Built on the VibeXR Interaction Framework v' + version + '.\n\n'
     f'  VibeXR Interaction Framework v{version} - single-file build')
swap('<h1>VibeXR</h1>', '<h1>Archiscape Quest</h1>')
# the shared landing page: card on the left, the scene framed beside it, the latest update on the card
sys.path.insert(0, str(P.parent / 'vibexr'))
import landing  # noqa: E402
s = landing.apply(s, updated='17 Oct 2026', notes='prototype, level 1: the Wooden Horse. Build a ramp over the walls of Troy with as few blocks as you can; the soldiers open the gate and the horse rolls in')
swap('<p class="sub">Interaction framework &middot; see-through by default &middot; hands, controllers &amp; gaze pointers</p>',
     '<p class="sub">Build the way, then let them walk it &middot; tap to build, hold to remove &middot; '
     'level 1: the Wooden Horse at Troy</p>\n'
     '    <p class="by">by <a href="https://rongxuanmu.com/" target="_blank" rel="noopener">Rongxuan Mu</a> '
     '&middot; built on Archiscape and the VibeXR interaction framework</p>')
swap('  #ver {', '  .by { margin: -10px 0 18px; font-size: 13px; color: rgba(255,255,255,0.5); }\n'
     '  .by a { color: rgba(255,255,255,0.85); text-decoration: none; border-bottom: 1px solid rgba(255,255,255,0.35); }\n'
     '  #ver {')
swap(re.search(r'"WebXR not available - desktop preview \([^"]*\)"', s).group(0),
     '"Desktop preview: click to build, hold to remove, G go, Z undo, R reset, right-drag look, WASD fly"')
swap('document.getElementById("ver").textContent = `v${VERSION}`;',
     'document.getElementById("ver").textContent = `Archiscape Quest \\u00b7 VibeXR v${VERSION}`;')
swap('this.camera.position.set(0, 1.95, 0.7);', 'this.camera.position.set(0.2, 1.95, 0.45);')
swap('this.controls.target.set(0, 1.6, -0.5);', 'this.controls.target.set(0.2, 1.47, -0.5);')

# single-module sanity: no binding imported twice
names = re.findall(r'^import (?:\* as (\w+)|\{([^}]*)\}|(\w+)) from', s, re.M)
bound = []
for star, group, default in names:
    if star:
        bound.append(star)
    elif default:
        bound.append(default)
    else:
        bound += [x.split(' as ')[-1].strip() for x in group.split(',') if x.strip()]
dupes = {n for n in bound if bound.count(n) > 1}
assert not dupes, f'duplicate import bindings: {dupes}'
assert 'enter-vr' not in s and 'VR only' not in s, 'VibeXR pages have exactly one Enter button'

page = f'''<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<meta name="robots" content="noindex, nofollow">
<title>Archiscape Quest</title>
<link rel="icon" href="../Resources/common/Rongxuan.jpeg" type="image/jpeg">
</head>
<body>
<!-- Generated by archiscape-quest/build.py from archiscape/src/*.js, src/quest.js and vibexr/codepen.html. -->
{s.rstrip()}
</body>
</html>
'''
(P / 'index.html').write_text(page)
print(f'archiscape-quest/index.html built (framework v{version}, {len(s) / 1024:.0f} KB)')
